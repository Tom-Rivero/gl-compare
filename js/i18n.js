export function detectLang(langs) {
  for (const l of langs || []) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (LANGS.includes(code)) return code;
  }
  return "en";
}

// pref = "auto" (langue du téléphone) ou un code de LANGS
export function setLang(pref) {
  lang = LANGS.includes(pref) ? pref : detectLang(globalThis.navigator?.languages ?? [globalThis.navigator?.language]);
  if (globalThis.document) document.documentElement.lang = lang;
  return lang;
}

export const locale = () => LOCALES[lang];

export function t(key, params = {}) {
  const s = DICT[lang][key] ?? DICT.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => params[k] ?? m);
}

export function translatePage() {
  document.querySelectorAll("[data-i18n]").forEach(el => el.textContent = t(el.dataset.i18n));
  document.querySelectorAll("[data-i18n-aria]").forEach(el => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  document.title = t("app.title");
}

export const dictionaries = DICT;
